import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

import { SOURCE_POLICY, TARGET_CATEGORIES } from './lib/libraryCandidates.js'

const root = path.resolve(import.meta.dirname, '..')
const manifestPath = path.join(root, 'src', 'data', 'archiveLibraryVerified.json')
const outputDir = path.join(root, 'src', 'data', 'generated')
const outputPath = path.join(outputDir, 'archiveLibrary.js')

const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
if (!Array.isArray(manifest.records)) throw new Error(`No records in ${manifestPath}`)

function slug(value) {
  return (
    String(value || '')
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '') || 'unknown'
  )
}

const authors = []
const seenAuthors = new Set()

const titles = manifest.records.map((record) => {
  const authorId = slug(record.author)
  if (!seenAuthors.has(authorId)) {
    seenAuthors.add(authorId)
    authors.push({
      id: authorId,
      name: record.author,
      nameUr: '',
      role: 'Author',
      bio: ''
    })
  }

  const titleId = slug(record.id)
  const rightsNote = record.rights?.licenseUrl
    ? ` Reuse terms: ${record.rights.licenseUrl}.`
    : ''

  return {
    id: titleId,
    number: record.id,
    name: record.title,
    nameUr: record.urduTitle || record.title,
    seriesId: null,
    voiceId: 'pk-male',
    authorId,
    genres: [record.category],
    kind: 'Audiobook',
    lang: 'ur',
    featured: false,
    top: false,
    year: null,
    coverUrl: record.coverUrl || '',
    synopsis: `Verified Urdu audiobook from the Internet Archive.${rightsNote}`,
    sourceUrl: record.archiveItemUrl,
    sourceLabel: 'Internet Archive',
    rights: record.rights,
    episodes: [
      {
        id: `${titleId}-e1`,
        title: record.urduTitle || record.title,
        titleEn: record.title,
        duration: Math.max(1, Math.round((record.durationSeconds || 0) / 60)),
        durationSeconds: record.durationSeconds || 0,
        free: true,
        asset: record.assetId,
        audio: record.directMp3Url,
        codec: 'opus',
        kbps: 32,
        channels: 'mono'
      }
    ]
  }
})

const counts = TARGET_CATEGORIES.map(({ id, label, target }) => ({
  id,
  label,
  target,
  published: titles.filter((title) => title.genres.includes(label)).length
}))

const banner = [
  '// Generated by scripts/build-library-catalogue.mjs — do not edit by hand.',
  `// Source: src/data/archiveLibraryVerified.json (${SOURCE_POLICY}).`,
  ''
].join('\n')

const body = `${banner}
export const archiveTitles = ${JSON.stringify(titles, null, 2)}

export const archiveAuthors = ${JSON.stringify(authors, null, 2)}

export const archiveCategoryCounts = ${JSON.stringify(counts, null, 2)}

export const archivePublishedCount = ${titles.length}
`

mkdirSync(outputDir, { recursive: true })
writeFileSync(outputPath, body)
process.stdout.write(
  `Generated ${titles.length} title(s), ${authors.length} author(s) → ${path.relative(root, outputPath)}\n`
)
