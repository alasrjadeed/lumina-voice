// Generates a store-only .env from public production values.
// Vite inlines every VITE_* variable into the bundle, so radio/broadcast keys
// are explicitly blanked here even when .env.local defines them for local use.

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const OUTPUT = resolve(ROOT, '.env.store')

function envFile(name) {
  const path = resolve(ROOT, name)
  if (!existsSync(path)) return {}
  const out = {}
  for (const line of readFileSync(path, 'utf8').split(/\r?\n/)) {
    const match = line.match(/^\s*(VITE_[A-Z0-9_]+)\s*=\s*(.*?)\s*$/i)
    if (!match) continue
    const value = match[2].replace(/^['"]|['"]$/g, '')
    if (value) out[match[1]] = value
  }
  return out
}

const env = {
  ...envFile('.env'),
  ...envFile('.env.local'),
  ...envFile('.env.production')
}

const value = (key) => String(env[key] || '').trim()

const lines = [
  '# Generated by scripts/prepare-store-env.mjs — do not edit by hand.',
  '# Radio and broadcast values are blanked so they cannot enter the store bundle.',
  'VITE_RADIO_ENABLED=false',
  'VITE_CATALOGUE_SNAPSHOT_URL=/catalogue.json',
  `VITE_SUPABASE_URL=${value('VITE_SUPABASE_URL')}`,
  `VITE_SUPABASE_PUBLISHABLE_KEY=${value('VITE_SUPABASE_PUBLISHABLE_KEY') || value('VITE_SUPABASE_ANON_KEY')}`,
  `VITE_SUPABASE_ANON_KEY=${value('VITE_SUPABASE_ANON_KEY')}`,
  'VITE_LOG_LEVEL=warn',
  'VITE_SENTRY_DSN=',
  'VITE_SENTRY_ENVIRONMENT=production',
  'VITE_SENTRY_TRACES_SAMPLE_RATE=0',
  'VITE_APP_VERSION=1.0.0',
  'VITE_AZURACAST_API_KEY=',
  'VITE_AZURACAST_API_URL=',
  'VITE_AZURACAST_BASE_URL=',
  'VITE_AZURACAST_SHORTCODE=',
  'VITE_AZURACAST_STATION_ID=',
  'VITE_RADIO_STREAM_URL=',
  'VITE_STREAM_LISTEN_BASE=',
  'VITE_STREAM_LISTEN_URL=',
  'VITE_STREAM_PROVIDER='
]

writeFileSync(OUTPUT, `${lines.join('\n')}\n`, { mode: 0o600 })
process.stdout.write(`store env generated: ${OUTPUT}\n`)
